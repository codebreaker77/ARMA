def stratified_sample_trajectories(df: pd.DataFrame, n_samples: int = SAMPLE_N, seed: int = RANDOM_SEED) -> pd.DataFrame:
    """Sample n_samples stratified across repos using Hare-Niemeyer (largest remainder) allocation."""
    rng = np.random.RandomState(seed)
    total_n = len(df)
    repo_counts = df["repo"].value_counts()
    
    # Proportional quotas
    quotas = {repo: (count / total_n) * n_samples for repo, count in repo_counts.items()}
    allocations = {repo: int(np.floor(q)) for repo, q in quotas.items()}
    remainders = {repo: quotas[repo] - allocations[repo] for repo in quotas}
    
    allocated = sum(allocations.values())
    shortfall = n_samples - allocated
    
    # Allocate remainder to largest fractions; break ties deterministically by repo name
    sorted_repos = sorted(remainders.keys(), key=lambda r: (remainders[r], r), reverse=True)
    for i in range(shortfall):
        allocations[sorted_repos[i]] += 1
        
    sampled_indices = []
    for repo, alloc in allocations.items():
        if alloc == 0:
            continue
        repo_indices = df.index[df["repo"] == repo].values
        # Sample without replacement
        chosen = rng.choice(repo_indices, size=alloc, replace=False)
        sampled_indices.extend(chosen)
        
    sampled_df = df.loc[sampled_indices].copy()
    # Deterministic shuffle of the sampled set
    sampled_df = sampled_df.sample(frac=1.0, random_state=seed).reset_index(drop=True)
    return sampled_df

def run_audit():
    print("=" * 80)
    print("PHASE 0: DATASET AUDIT & STRATIFICATION")
    print(f"Dataset: {DATASET_NAME} (Revision: {DATASET_REVISION})")
    print("=" * 80)
    
    t0 = time.time()
    raw_path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "data", "rg0.parquet")
    if not os.path.exists(raw_path):
        raise FileNotFoundError(f"Missing cached parquet file: {raw_path}")
        
    print("\n--- SCHEMA AUDIT & FIELD CLASSIFICATION ---")
    for field, meta in SCHEMA_CLASSIFICATION.items():
        print(f"  * {field:<24} [{meta['type']:<18}] -> {meta['class']:<35}")
        print(f"    {meta['description']}")
        
    print("\nLoading dataset partition...")
    tbl = pq.read_table(raw_path)
    df_raw = tbl.to_pandas()
    print(f"Loaded {len(df_raw)} records from {df_raw['repo'].nunique()} unique repositories in {time.time()-t0:.2f}s.")
    
    print(f"\nPerforming stratified sampling (N={SAMPLE_N}, seed={RANDOM_SEED}) across repositories...")
    df_sampled = stratified_sample_trajectories(df_raw, n_samples=SAMPLE_N, seed=RANDOM_SEED)
    
    # Assign Dev vs Test split strictly by repo hash
    df_sampled["repo_hash"] = df_sampled["repo"].apply(get_repo_hash_val)
    df_sampled["split"] = df_sampled["repo"].apply(lambda r: "dev" if is_dev_repo(r) else "test")
    
    dev_df = df_sampled[df_sampled["split"] == "dev"]
    test_df = df_sampled[df_sampled["split"] == "test"]
    
    # Compute step counts and estimated tokens
    print("\nComputing trajectory lengths and token distributions (tiktoken cl100k_base proxy)...")
    step_counts = []
    token_estimates = []
    for traj in df_sampled["trajectory"]:
        step_counts.append(len(traj))
        t_tok = sum(estimate_message_tokens(m) for m in traj)
        token_estimates.append(t_tok)
        
    df_sampled["step_count"] = step_counts
    df_sampled["estimated_tokens"] = token_estimates
    
    # Save sampled dataset for subsequent offline experiments
    pq.write_table(pa.Table.from_pandas(df_sampled), SAMPLED_DATA_PATH)
    print(f"Saved stratified dataset to {SAMPLED_DATA_PATH}")
    
    # Metrics computation
    total_n = len(df_sampled)
    resolved_ratio = float(df_sampled["resolved"].mean())
    res_ci_low, res_ci_high = cluster_bootstrap_ci(
        df_sampled, lambda d: float(d["resolved"].mean()), group_col="repo", n_resamples=1000, seed=RANDOM_SEED
    )
    
    dev_resolved = float(dev_df["resolved"].mean())
    test_resolved = float(test_df["resolved"].mean())
    
    dev_repos = dev_df["repo"].nunique()
    test_repos = test_df["repo"].nunique()
    total_repos = df_sampled["repo"].nunique()
    
    # Step count stats
    steps = df_sampled["step_count"]
    steps_mean = float(steps.mean())
    steps_median = float(steps.median())
    steps_p25 = float(steps.quantile(0.25))
    steps_p75 = float(steps.quantile(0.75))
    steps_min = int(steps.min())
    steps_max = int(steps.max())
    
    # Token stats (estimates)
    tokens = df_sampled["estimated_tokens"]
    tok_mean = float(tokens.mean())
    tok_median = float(tokens.median())
    tok_p25 = float(tokens.quantile(0.25))
    tok_p75 = float(tokens.quantile(0.75))
    tok_total = int(tokens.sum())
    
    results = {
        "dataset_name": DATASET_NAME,
        "dataset_revision": DATASET_REVISION,
        "sample_n": total_n,
        "total_repos": total_repos,
        "resolved_ratio": resolved_ratio,
        "resolved_ratio_95ci": [res_ci_low, res_ci_high],
        "split_sizes": {
            "dev_trajectories": len(dev_df),
            "dev_fraction": len(dev_df) / total_n,
            "dev_repos": dev_repos,
            "dev_resolved_ratio": dev_resolved,
            "test_trajectories": len(test_df),
            "test_fraction": len(test_df) / total_n,
            "test_repos": test_repos,
            "test_resolved_ratio": test_resolved,
        },
        "step_distribution": {
            "mean": steps_mean,
            "median": steps_median,
            "p25": steps_p25,
            "p75": steps_p75,
            "min": steps_min,
            "max": steps_max,
        },
        "token_distribution_estimate": {
            "proxy": "tiktoken_cl100k_base",
            "mean": tok_mean,
            "median": tok_median,
            "p25": tok_p25,
            "p75": tok_p75,
            "total_tokens": tok_total,
        },
        "compute_time_seconds": time.time() - t0,
    }
    
    res_path = os.path.join(RESULTS_DIR, "phase0_audit.json")
    with open(res_path, "w", encoding="utf-8") as f:
        json.dump(results, f, indent=2)
        
    print("\n" + "=" * 80)
    print("PHASE 0 AUDIT SUMMARY")
    print("=" * 80)
    print(f"Total Trajectories (n): {total_n}")
    print(f"Total Repositories:     {total_repos}")
    print(f"Resolved Ratio:         {resolved_ratio*100:.2f}% (95% Cluster CI: [{res_ci_low*100:.2f}%, {res_ci_high*100:.2f}%], n={total_n})")
    print(f"Dev Split:              {len(dev_df)} runs ({len(dev_df)/total_n*100:.1f}%), {dev_repos} repos, {dev_resolved*100:.2f}% resolved")
    print(f"Frozen Test Split:      {len(test_df)} runs ({len(test_df)/total_n*100:.1f}%), {test_repos} repos, {test_resolved*100:.2f}% resolved")
    print(f"Step Count (Steps):     mean={steps_mean:.1f}, median={steps_median:.0f}, IQR=[{steps_p25:.0f}, {steps_p75:.0f}], min={steps_min}, max={steps_max}")
    print(f"Token Estimate (Proxy): mean={tok_mean:.0f}, median={tok_median:.0f}, IQR=[{tok_p25:.0f}, {tok_p75:.0f}], total={tok_total:,}")
    print(f"Audit results written to: {res_path}")
    print(f"Compute Time:           {results['compute_time_seconds']:.2f}s")
    print("=" * 80)
    return results

if __name__ == "__main__":
    run_audit()
